def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    pool = POOL.read_text(encoding="utf-8")
    changed = 0
    missing = []
    for old, new in BOTTOM_FIX.items():
        # 旧文案在源码里是一个带引号的整串
        needle = f'"{old}"'
        if needle not in pool:
            missing.append(old)
            continue
        pool = pool.replace(needle, f'"{new}"', 1)
        changed += 1

    print(f"build_pool.py 下格补写 {changed} 条")
    if missing:
        print(f"  !! 没找到 {len(missing)} 条：")
        for m in missing:
            print(f"     {m}")

    if args.write:
        POOL.write_text(pool, encoding="utf-8")
        print(f"已写回 {POOL}")
        subprocess.run([sys.executable, str(ROOT / "pipeline" / "build_pool.py"), "--write"],
                       check=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
